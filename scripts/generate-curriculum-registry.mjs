/**
 * Regenerates src/lib/curriculum/registry.ts (one static import per JSON file
 * in src/lib/curriculum/cbse-2026-27) and src/lib/curriculum/exams/registry.ts
 * (one per exam syllabus). Static imports so the bundler can include them.
 *
 *   node scripts/generate-curriculum-registry.mjs
 */
import { readdirSync, writeFileSync } from 'node:fs';

const dir = 'src/lib/curriculum/cbse-2026-27';
const files = readdirSync(dir).filter(f => f.endsWith('.json')).sort();
const ident = f => 's_' + f.replace(/\.json$/, '').replace(/[^a-z0-9]/gi, '_');
const out = `// Generated by scripts/generate-curriculum-registry.mjs. Do not edit by hand.
import type { CurriculumSubject } from './types';

${files.map(f => `import ${ident(f)} from './cbse-2026-27/${f}';`).join('\n')}

export const SUBJECT_FILES = [
${files.map(f => `  ${ident(f)},`).join('\n')}
] as unknown as CurriculumSubject[];
`;
writeFileSync('src/lib/curriculum/registry.ts', out);
console.log(`registry.ts: ${files.length} subjects`);

// Competitive exam syllabi (src/lib/curriculum/exams/*.json)
const exDir = 'src/lib/curriculum/exams';
const exFiles = readdirSync(exDir).filter(f => f.endsWith('.json')).sort();
const exIdent = f => 'e_' + f.replace(/\.json$/, '').replace(/[^a-z0-9]/gi, '_');
writeFileSync(`${exDir}/registry.ts`, `// Generated by scripts/generate-curriculum-registry.mjs. Do not edit by hand.
import type { ExamSyllabus } from './types';

${exFiles.map(f => `import ${exIdent(f)} from './${f}';`).join('\n')}

export const EXAM_FILES = [
${exFiles.map(f => `  ${exIdent(f)},`).join('\n')}
] as unknown as ExamSyllabus[];
`);
console.log(`exams/registry.ts: ${exFiles.length} exams`);
